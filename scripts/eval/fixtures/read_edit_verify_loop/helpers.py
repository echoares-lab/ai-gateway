"""Sample helpers module. The task requires counting the def statements here."""


def add(a, b):
    return a + b


def subtract(a, b):
    return a - b


def multiply(a, b):
    return a * b


def divide(a, b):
    return a / b


def square(a):
    return a * a


def is_even(n):
    return n % 2 == 0
